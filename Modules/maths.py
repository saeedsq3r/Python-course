import math

# Square root of a number
print(math.sqrt(25))

# Power: 2^3 = 8
print(math.pow(2, 3))

# Factorial: 5! = 120
print(math.factorial(5))

# Ceiling value (round up)
print(math.ceil(4.3))

# Floor value (round down)
print(math.floor(4.9))

# Value of Pi
print(math.pi)

# Euler's number
print(math.e)

# Absolute value
print(math.fabs(-10))

# Natural logarithm
print(math.log(10))

# Log base 10
print(math.log10(100))

# Sine of angle (radians)
print(math.sin(math.pi/2))

# Cosine of angle
print(math.cos(0))

# Tangent of angle
print(math.tan(0))

# Convert radians to degrees
print(math.degrees(math.pi))

# Convert degrees to radians
print(math.radians(180))

# Greatest Common Divisor
print(math.gcd(12, 18))

# Least Common Multiple
print(math.lcm(4, 6))

# Integer square root
print(math.isqrt(16))

# Exponential value e^x
print(math.exp(2))

# Distance between two points
print(math.dist([0,0], [3,4]))